// עזר לפרק 1: בלוק "🧮 עכשיו באקסל המלווה", שמפנה לגיליון ולשורה לפי חוזה הגיליונות
// (_עבודת לילה\תאריכים 07.11\רץ ב\חוזה גיליונות.md). משנים שם גיליון? משנים כאן פעם אחת.
// האות היא התיאור של המשימה בגיליון (שורה א, ב, ג...), ולא מספר שורה, כמו calcRef באחוזים.

export const XL_FILE = 'דף עבודה - תאריכים ושעות.xlsx';

export const SHEET_NAMES = {
  1: 'תאריך הוא מספר',
  2: 'שעות',
  3: 'הזנה ועיצוב',
  4: 'תאריך שבור',
  5: 'לפרק',
  6: 'TEXT',
  7: 'היום ועכשיו',
  8: 'לבנות תאריך',
};

// task(1, 'א–ד', 'מה עושות ומה רואות')
export function task(sheet, rows, text) {
  return {
    type: 'text',
    html: `<div class="dt-task"><b>🧮 עכשיו באקסל המלווה</b><br>
      גיליון <b>${sheet}</b> (${SHEET_NAMES[sheet]}), ${rows.includes('–') || rows.includes(',') ? 'שורות' : 'שורה'} <b>${rows}</b>.<br>${text}</div>`,
  };
}

// 16.11: שקף אחרון משלו בכל יחידה, "🧮 עכשיו לאקסל". קודם הבלוק ישב באמצע השקף האחרון, ליד שאלה על משהו אחר,
// ומי שעבד מהלומדה לא ידע מתי לעבור לגיליון. השאלה לא בודקת ידע: היא מזכירה את הסדר (יחידה ← גיליון ← יחידה הבאה).
// אין בה חסימה של ממש, ותשובה אחת מספיקה כדי להמשיך. כפתור ההורדה כאן, כי הכול פתוח ואפשר להגיע ליחידה בלי לעבור ביחידה 0.
// taskSlide(5, 'א–ה', 'מה עושים בגיליון')
export function taskSlide(sheet, rows, text) {
  const right = { text: `עוברות לגיליון ${sheet} באקסל, עושות את השורות ובודקות שיש ✔`, correct: true };
  const wrong = [
    { text: 'ממשיכות ישר ליחידה הבאה בלומדה', correct: false, hint: `רגע, קודם הגיליון. בגיליון ${sheet} מתרגלות בעצמכן את מה שלמדנו עכשיו, ואחר כך ממשיכות ליחידה הבאה.` },
    { text: 'מורידות קובץ חדש לכל יחידה', correct: false, hint: `אין צורך. זה אותו קובץ לכל הפרק, ובו גיליון ${sheet}.` },
  ];
  const options = [...wrong];
  options.splice(sheet % 3, 0, right);   // התשובה הנכונה לא תמיד באותו מקום
  return {
    blocks: [
      { type: 'text', html: `<h2>🧮 עכשיו לאקסל: גיליון ${sheet}</h2>
        <p>סיימתן את ההסבר. עכשיו מתרגלות בעצמכן, באקסל המלווה.</p>` },
      task(sheet, rows, text),
      { type: 'download', file: XL_FILE, label: 'דף עבודה: תאריכים ושעות', note: 'כבר הורדתן ביחידה 0? משתמשות באותו קובץ' },
      { type: 'text', html: '<p>✔ בכל השורות? חוזרות ללומדה, ליחידה הבאה.</p>' },
    ],
    question: { type: 'mc', prompt: 'מה עושים עכשיו?', options },
  };
}
